import { test, expect } from '@playwright/test';

test('test', async ({ page }) => {
  await page.goto('https://eventhub.rahulshettyacademy.com/login');
  await page.getByRole('textbox', { name: 'Email' }).click();
  await page.getByRole('textbox', { name: 'Email' }).fill('lucky.udaya123@gmail.com');
  await page.getByRole('textbox', { name: 'Password' }).click();
  await page.getByRole('textbox', { name: 'Password' }).press('CapsLock');
  await page.getByRole('textbox', { name: 'Password' }).fill('Lucky@123');
  await page.getByRole('button', { name: 'Sign In' }).click();
  await page.getByRole('article').filter({ hasText: 'ConferenceFeaturedWorld Tech' }).getByTestId('book-now-btn').click();
  await page.getByRole('textbox', { name: 'Full Name*' }).click();
  await expect(page.getByRole('heading', { name: 'World Tech Summit' })).toBeVisible();
  await expect(page.getByText('City', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm Booking' }).click();
  await expect(page.getByText('Name must be at least 2 chars')).toBeVisible();
  await page.getByText('Enter a valid email').click();
  await page.getByText('Enter a valid 10-digit phone').click();
  await page.getByRole('textbox', { name: 'Full Name*' }).click();
  await page.getByRole('textbox', { name: 'Full Name*' }).fill('ud123');
  await page.getByTestId('customer-email').click();
  await page.getByTestId('customer-email').fill('lucky.udaya1233@gmail.com');
  await page.getByRole('textbox', { name: 'Phone Number*' }).click();
  await page.getByRole('textbox', { name: 'Phone Number*' }).fill('+91-1234567899');
  await page.getByRole('button', { name: 'Confirm Booking' }).click();
  await expect(page.getByRole('heading', { name: 'Booking Confirmed! 🎉' })).toBeVisible();
  await expect(page.getByText('Your tickets are reserved.')).toBeVisible();
  await expect(page.getByRole('main')).toContainText('W-3V7O71');
  await expect(page.getByRole('main')).toContainText('ud123');
  await expect(page.getByRole('main')).toContainText('1');
  await expect(page.getByRole('main')).toContainText('$1,500');
  await page.getByRole('button', { name: 'View My Bookings' }).click();
  await expect(page.getByText('confirmed')).toBeVisible();
  await expect(page.getByTestId('booking-id')).toBeVisible();
  await page.getByTestId('cancel-booking-btn').click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByTestId('cancel-booking-btn').click();
  await page.getByTestId('confirm-dialog-yes').click();
  await expect(page.getByRole('button', { name: 'Clear all bookings' })).toBeVisible();
});